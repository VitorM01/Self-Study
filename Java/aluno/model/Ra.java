package model;

public class Ra {
    int numero;
    int anoFeito;

    public Ra(int numero, int anoFeito){
        this.numero = numero;
        this.anoFeito = anoFeito;
    }

    public int getNumero() {
        return numero;
    }
    public void setNumero(int numero) {
        this.numero = numero;
    }
    public int getAnoFeito() {
        return anoFeito;
    }
    public void setAnoFeito(int anoFeito) {
        this.anoFeito = anoFeito;
    }
    
}
